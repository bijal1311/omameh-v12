export const body = String.raw`
  <p class="drop">People assumed two things. That something must have gone wrong. And that I would be going into consulting.</p>
  <p>The second is easier, so I will start there. No. And the reason is the reason for all of it.</p>

  <span class="snum">I</span>
  <h2 class="art-h tight">I had wanted to build something for years.</h2>
  <p>Not recently. For years.</p>
  <p>It sat in my head long enough that I stopped treating it as a plan and started treating it as something I thought about on planes.</p>
  <p>I liked the work. I liked building teams that outran themselves. I liked walking into a problem nobody had named and naming it. I liked backing people early and watching them get further than they expected to — that one more than the rest.</p>
  <p>And underneath all of it, the thing I could not put down. I wanted to build one of my own.</p>
  <p>So the question was never whether. It was when.</p>

  <span class="snum">II</span>
  <h2 class="art-h tight">The answer was not courage.</h2>
  <p>I used to think I was waiting for nerve. I was not.</p>
  <p>I was waiting until I had the time, the experience, the skills and the resilience to do it properly. And until I could afford to start it for the right reasons rather than the urgent ones.</p>
  <p>Those are four different things and they arrive at different speeds. Skills came first. Experience took longer. Resilience took longest, and I only know I had it because of what the last six months have asked for.</p>

  <div class="pull"><p>You do not leave a good career because it stops being good. You leave when you are carrying enough to build something that holds.</p></div>

  <p>Which means the twenty years were not what I escaped. They were what made it possible. Every operating model I inherited and had to fix. Every transformation I watched stall. Every restructure I sat inside. That is the raw material, and I did not walk away from it. I brought it.</p>

  <span class="snum">III</span>
  <h2 class="art-h tight">The same law, somewhere else.</h2>
  <p>They would buy the technology. They would hire the talent. Nothing would change. Then everyone would look for someone to blame.</p>
  <p>It was almost never the technology. It was almost never the talent.</p>
  <p><strong>It was that the organisation was not built to carry what it had just bought.</strong></p>
  <p>Careers work the same way and almost nobody says so.</p>
  <p>If you are stuck, you have probably decided it is because you are not good enough, not visible enough, or not lucky. It is usually none of those. It is that you are trying to carry something you have not yet built the structure for.</p>
  <p>Or — and this is the more common one — you are already carrying plenty and have not noticed.</p>

  <div class="pull"><p>Effort is not the lever. Capacity is.</p></div>

  <span class="snum">IV</span>
  <h2 class="art-h tight">What I got known for.</h2>
  <p>Over twenty years you acquire a reputation whether you manage it or not. Mine came down to a few lines, and I heard them often enough to know they were real.</p>
  <p><em>If you need a difficult programme mobilised, give it to her.</em></p>
  <p><em>If you want people who will be running things in ten years, put them in her team.</em></p>
  <p><em>If you want radical candour, work with her.</em></p>
  <p>And the fourth, which is the third said by someone who meant it differently.</p>
  <p><em>If you do not want to hear the straight version, she is not for you.</em></p>
  <p>That one cost me rooms. There were conversations I was not in, and I knew at the time which ones and why.</p>
  <p>It was not always comfortable. It was not always good. But it was me, and I was never willing to trade it.</p>

  <span class="snum">V</span>
  <h2 class="art-h tight">Which brings me back to the question.</h2>
  <p>I had the equipment for a while before I moved.</p>
  <p>That is the honest part. I had a list of reasons to wait and every one was reasonable. One more cycle. One more year. One more thing to see through. I could have defended any of them in a boardroom. I did, to myself, repeatedly.</p>
  <p>Then my eight-year-old asked me why I had not done it yet.</p>
  <p>I gave her the reasons. She listened to all of them and said: <em>why not?</em></p>
  <p>I have sat in rooms with boards. I have defended business cases I did not fully believe in, and won.</p>
  <p><strong>I did not have an answer for an eight-year-old.</strong></p>
  <p>She did not make me ready. I was already ready. What she took away was the need for permission — and there was nobody left to give it to me anyway.</p>

  <span class="snum">VI</span>
  <h2 class="art-h tight">Six months in.</h2>
  <p>It is hard. Every day, and I am not going to pretend otherwise. Anyone who tells you the first year of building something is a relief has not built anything.</p>
  <p>But the hard part is not the one I expected. It is not the money, or the hours, or the not knowing.</p>
  <p>It is the unlearning.</p>
  <p>Twenty years of muscle memory, and the strongest of it is this. I still catch myself waiting for a decision that is mine to make. Looking up for a sign-off from someone who is not there. The pause is only a second or two now. It used to be most of a day.</p>
  <p>That reflex was an asset for twenty years. Checking, aligning, bringing people with you — that is most of what good operating leadership is, and I was good at it. It is also the most expensive habit to carry into something of your own, because there is nobody above you and the waiting is pure cost.</p>
  <p>Relearning is the easy half. It is additive. It feels like progress and you can put it on a list.</p>
  <p><strong>Unlearning is subtractive.</strong> You put down the thing that got you here, and nothing replaces it for a while.</p>
  <p>That is what this is called, and that is why.</p>
  <p>And here is the part I did not plan for.</p>
  <p>The thing that occasionally cost me rooms is now the thing people pay for. Boards do not need another adviser who will agree with them expensively. They need someone who will say the structural truth early enough to be useful.</p>
  <p>I spent twenty years being told it was a strong flavour.</p>
  <p>I have built a business where it is the service.</p>
`;

